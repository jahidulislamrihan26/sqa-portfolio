// Builds docs/traceability.md: which cases of the manual test suite are automated, and by which tests.
// It lists the real tests with `playwright test --list`, so tests generated in loops are included.
// A test is linked to a manual case by [TC-nnn] in its title, and to a defect by [BUG-nnn].   Usage: node tools/trace.js
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const MANUAL = path.join(ROOT, '..', 'manual-testing', 'test-suite', 'test-cases.csv');

// minimal CSV reader (quotes and commas inside quotes)
function parseCsv(text) {
  const rows = []; let row = [], cell = '', q = false;
  text = text.replace(/^﻿/, '');
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') q = false; else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(cell); rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}
const [head, ...body] = parseCsv(fs.readFileSync(MANUAL, 'utf8')).filter((r) => r.length > 1);
const col = (n) => head.indexOf(n);
const manual = body.map((r) => ({ id: r[col('ID')], module: r[col('Module')], title: r[col('Title')], status: r[col('Status')], defect: r[col('Defect')] }));

const list = spawnSync(process.execPath, [path.join(ROOT, 'node_modules', '@playwright', 'test', 'cli.js'), 'test', '--list', '--reporter=json', '--project=chromium'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const json = JSON.parse(list.stdout);
const tests = [];
(function walk(s) { for (const x of s.suites || []) walk(x); for (const sp of s.specs || []) if (!/auth\.setup/.test(sp.file)) tests.push({ title: sp.title, file: sp.file, line: sp.line }); })({ suites: json.suites }); // the one-time login setup is not a test

const byTc = {};
for (const t of tests) for (const m of t.title.matchAll(/\[(TC-\d+)\]/g)) (byTc[m[1]] = byTc[m[1]] || []).push(t);
const bugOf = (t) => (t.title.match(/\[(BUG-\d+)\]/) || [])[1];
const manualIds = new Set(manual.map((m) => m.id));
const unknown = Object.keys(byTc).filter((id) => !manualIds.has(id));

// Cases that cannot be automated, or are covered by running the whole suite in each browser project.
const NOT_AUTOMATED = {
  'TC-061': 'Covered by running the whole suite on the chromium project (CI matrix).',
  'TC-062': 'Covered by running the whole suite on the firefox project (CI matrix).',
  'TC-063': 'Covered by `EDGE=1 npx playwright test --project=edge` on a machine with Edge (not in CI).',
  'TC-064': 'Covered by running the whole suite on the webkit project (CI matrix).',
};
const rows = manual.map((m) => {
  const found = byTc[m.id] || [];
  const state = found.length ? (found.every((t) => /@known-bug/.test(t.title)) ? 'Automated, known defect' : 'Automated') : NOT_AUTOMATED[m.id] ? 'Covered by project matrix' : 'Manual only';
  return { ...m, found, state };
});
const n = (s) => rows.filter((r) => r.state === s).length;
const automated = n('Automated') + n('Automated, known defect');
const covered = automated + n('Covered by project matrix');

const L = [];
L.push('# Traceability: manual test cases to automated tests', '');
L.push('Generated by `npm run trace` from the manual suite ([test-cases.csv](../../manual-testing/test-suite/test-cases.csv)) and the real list of tests. A test is linked to a manual case by `[TC-nnn]` in its title and to a defect by `[BUG-nnn]`.', '');
L.push(`**${automated} of ${rows.length} manual cases (${Math.round((100 * automated) / rows.length)}%) have at least one automated test; ${covered} (${Math.round((100 * covered) / rows.length)}%) counting the cases covered by the browser matrix.** ${tests.length} automated tests in total (chromium project), ${tests.filter((t) => /@known-bug/.test(t.title)).length} of them known-defect tests.`, '');
L.push('| Result | Manual cases |', '|---|---|', `| Automated (passing check) | ${n('Automated')} |`, `| Automated, captures a known defect (@known-bug) | ${n('Automated, known defect')} |`, `| Covered by the browser matrix | ${n('Covered by project matrix')} |`, `| Manual only | ${n('Manual only')} |`, '');
L.push('| Manual case | Title | Manual result | Automated | Tests |', '|---|---|---|---|---|');
for (const r of rows) {
  const links = r.found.slice(0, 3).map((t) => `${path.basename(t.file)}:${t.line}`).join(', ') + (r.found.length > 3 ? `, +${r.found.length - 3} more` : '');
  const bugs = [...new Set(r.found.map(bugOf).filter(Boolean))];
  L.push(`| ${r.id} | ${r.title.replace(/\|/g, '\\|')} | ${r.status}${r.defect ? ` (${r.defect})` : ''} | ${r.state}${bugs.length ? ` ${bugs.join(', ')}` : ''} | ${r.found.length ? links : NOT_AUTOMATED[r.id] || '-'} |`);
}
const manualOnly = rows.filter((r) => r.state === 'Manual only');
const WHY = {
  'TC-058': 'Comparing a layout needs a visual comparison with a stored baseline image; screenshots differ between operating systems and fonts, so this check stays manual (or needs per-platform baselines).',
};
L.push('', '## Manual only, and why', '');
for (const r of manualOnly) L.push(`- **${r.id}** ${r.title}. ${WHY[r.id] || 'Not automated yet.'}`);
if (unknown.length) L.push('', `**Warning:** these ids appear in test titles but not in the manual suite: ${unknown.join(', ')}`);
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'traceability.md'), L.join('\n') + '\n');
console.log(`Traceability: ${automated}/${rows.length} automated, ${covered}/${rows.length} with the browser matrix, ${manualOnly.length} manual only${unknown.length ? `, WARNING unknown ids: ${unknown.join(', ')}` : ''}`);
